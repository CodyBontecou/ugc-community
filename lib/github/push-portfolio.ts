import { Octokit } from "@octokit/rest";

// =====================================================
// Types
// =====================================================

export interface CreateRepoResult {
  repoFullName: string;
  repoUrl: string;
  repoId: number;
}

export interface PushFilesResult {
  commitSha: string;
  commitUrl: string;
}

export interface GitHubFile {
  path: string;
  content: string;
  /** If true, content is already base64-encoded binary data */
  isBinary?: boolean;
}

// =====================================================
// Repository Creation
// =====================================================

/**
 * Create a new GitHub repository for a creator's portfolio
 */
export async function createPortfolioRepo(
  octokit: Octokit,
  username: string,
  options?: {
    repoNameOverride?: string;
    description?: string;
    isPrivate?: boolean;
  }
): Promise<CreateRepoResult> {
  const repoName = options?.repoNameOverride || `${username}-portfolio`;
  const description =
    options?.description ||
    `Portfolio website for ${username} - Generated by UGC Community`;

  const { data: repo } = await octokit.repos.createForAuthenticatedUser({
    name: repoName,
    description,
    private: options?.isPrivate ?? true,
    auto_init: true, // Required for Git Data API to work
    has_issues: false,
    has_projects: false,
    has_wiki: false,
  });

  return {
    repoFullName: repo.full_name,
    repoUrl: repo.html_url,
    repoId: repo.id,
  };
}

// =====================================================
// File Pushing
// =====================================================

/**
 * Push multiple files to a GitHub repository in a single commit
 * Uses the Git Data API to create a tree and commit
 */
export async function pushFilesToRepo(
  octokit: Octokit,
  repoFullName: string,
  files: GitHubFile[],
  commitMessage: string,
  options?: {
    branch?: string;
  }
): Promise<PushFilesResult> {
  const [owner, repo] = repoFullName.split("/");
  const branch = options?.branch || "main";

  // Step 1: Get the latest commit SHA for the branch (or create initial commit)
  let baseTreeSha: string | undefined;
  let parentCommitSha: string | undefined;

  try {
    const { data: refData } = await octokit.git.getRef({
      owner,
      repo,
      ref: `heads/${branch}`,
    });
    parentCommitSha = refData.object.sha;

    // Get the tree SHA from the parent commit
    const { data: commitData } = await octokit.git.getCommit({
      owner,
      repo,
      commit_sha: parentCommitSha,
    });
    baseTreeSha = commitData.tree.sha;
  } catch {
    // Branch doesn't exist yet - this is fine for a new repo
    parentCommitSha = undefined;
    baseTreeSha = undefined;
  }

  // Step 2: Create blobs for each file
  const blobPromises = files.map(async (file) => {
    // For binary files (already base64), use content directly
    // For text files, encode to base64
    const content = file.isBinary
      ? file.content
      : Buffer.from(file.content).toString("base64");

    const { data: blob } = await octokit.git.createBlob({
      owner,
      repo,
      content,
      encoding: "base64",
    });
    return {
      path: file.path,
      sha: blob.sha,
    };
  });

  const blobs = await Promise.all(blobPromises);

  // Step 3: Create a new tree with all files
  const treeItems = blobs.map((blob) => ({
    path: blob.path,
    mode: "100644" as const,
    type: "blob" as const,
    sha: blob.sha,
  }));

  const { data: tree } = await octokit.git.createTree({
    owner,
    repo,
    tree: treeItems,
    base_tree: baseTreeSha,
  });

  // Step 4: Create the commit
  const commitParams: Parameters<typeof octokit.git.createCommit>[0] = {
    owner,
    repo,
    message: commitMessage,
    tree: tree.sha,
  };

  if (parentCommitSha) {
    commitParams.parents = [parentCommitSha];
  }

  const { data: commit } = await octokit.git.createCommit(commitParams);

  // Step 5: Update the branch reference (or create it)
  try {
    await octokit.git.updateRef({
      owner,
      repo,
      ref: `heads/${branch}`,
      sha: commit.sha,
    });
  } catch {
    // Branch doesn't exist, create it
    await octokit.git.createRef({
      owner,
      repo,
      ref: `refs/heads/${branch}`,
      sha: commit.sha,
    });
  }

  return {
    commitSha: commit.sha,
    commitUrl: commit.html_url,
  };
}

